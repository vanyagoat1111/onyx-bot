def esc(t):
    return html.escape(t, quote=False)


def task_block(i, t):
    title, how, yes, no = t
    return '\n'.join([
        '<section class="task">',
        '  <h3><span class="num">%02d</span> %s</h3>' % (i, esc(title)),
        '  <p class="how">%s</p>' % esc(how),
        '  <div class="pair">',
        '    <div class="cell yes"><p class="cell-h">Задача решена</p><p>%s</p></div>' % esc(yes),
        '    <div class="cell no"><p class="cell-h">Задача не решена</p><p>%s</p></div>' % esc(no),
        '  </div>',
        '</section>'])


def niche_block(k):
    d, c, n = DEMOS[k], CARD.get(k, {}), NICHE[k]
    has = '\n'.join('      <li>%s</li>' % esc(x) for x in c.get('has', []))
    return '\n'.join([
        '<section class="niche">',
        '  <p class="n-tag">%s %s</p>' % (c.get('emoji', '▪'), esc(d['tag'])),
        '  <h3 class="n-doubt">%s</h3>' % esc(n[0]),
        '  <p class="n-why">%s</p>' % esc(c.get('why', '')),
        '  <p class="n-lbl">Что должно быть на сайте</p>',
        '    <ul class="n-has">',
        has,
        '    </ul>',
        '  <div class="pair">',
        '    <div class="cell yes"><p class="cell-h">Если это есть</p><p>%s</p></div>' % esc(n[1]),
        '    <div class="cell no"><p class="cell-h">Если этого нет</p><p>%s</p></div>' % esc(n[2]),
        '  </div>',
        '  <a class="n-link" href="%s" target="_blank" rel="noopener">Посмотреть готовый сайт: %s →</a>'
        % (d['url'], esc(d['name'])),
        '</section>'])


def symptom_block():
    rows = '\n'.join(
        '    <div class="sym"><p class="sym-s">%s</p><p class="sym-c">%s</p></div>'
        % (esc(a), esc(b)) for a, b in SYMPTOMS)
    return '<section>\n  <div class="syms">\n%s\n  </div>\n</section>' % rows


