"""Сборка чек-листа ONYX «Как заказать сайт и не пожалеть».

Генератор, а не рукописный HTML: разметка живой галочки повторяется
больше ста раз, и держать её руками - гарантированный способ получить
расхождение в одном пункте из ста. Здесь текст лежит данными, оформление
одним шаблоном.
"""
import html, json, io, os

C = ('<li><label><input type="checkbox"><span class="box">'
     '<svg viewBox="0 0 12 12"><path d="M1.5 6.4 4.3 9.2 10.5 2.9"/></svg></span>'
     '<span class="t">{}</span></label></li>')

def checks(items, extra=''):
    body = '\n    '.join(C.format(html.escape(i)) for i in items)
    return '  <ul class="checks"%s>\n    %s\n  </ul>' % (extra, body)

def q(items):
    return '  <ul class="q">\n    %s\n  </ul>' % '\n    '.join(
        '<li>%s</li>' % html.escape(i) for i in items)

def steps(items):
    return '  <ol class="steps">\n    %s\n  </ol>' % '\n    '.join(
        '<li>%s</li>' % html.escape(i) for i in items)

def flags(items):
    return '  <ul class="flags">\n    %s\n  </ul>' % '\n    '.join(
        '<li>%s</li>' % html.escape(i) for i in items)

def note(text, warn=False):
    return '  <div class="note%s">%s</div>' % (' warn' if warn else '', text)

def p(text):
    return '  <p>%s</p>' % text

def part(n, title):
    return ('<div class="part">\n  <p class="part-n">%s</p>\n  <h2>%s</h2>\n</div>'
            % (html.escape(n), html.escape(title)))

def sec(num, title, *blocks):
    head = ('  <h3><span class="num">%s</span> %s</h3>' % (num, html.escape(title))
            if num else ('  <h3>%s</h3>' % html.escape(title) if title else ''))
    inner = '\n'.join([b for b in ([head] + list(blocks)) if b])
    return '<section>\n%s\n</section>' % inner

