"""Отраслевой гид ONYX «Сайт, которому доверяют» - стройка и ремонт.

Текст партнёра, оформление студии. Приём документа - пары «слабый вариант /
сильный вариант»: это его же структура, и она сильнее любого объяснения,
потому что человек узнаёт в левой колонке свой текущий сайт.

Собирается генератором по той же причине, что и остальные материалы:
разметка пары и галочки повторяются десятки раз.
"""
import html, os, tempfile

def esc(t):
    return html.escape(t, quote=False)

CHK = ('<li><label><input type="checkbox"><span class="box">'
       '<svg viewBox="0 0 12 12"><path d="M1.5 6.4 4.3 9.2 10.5 2.9"/></svg></span>'
       '<span class="t">{}</span></label></li>')

def checks(items, gid=''):
    return ('  <ul class="checks"%s>\n    %s\n  </ul>'
            % (gid, '\n    '.join(CHK.format(esc(i)) for i in items)))

def pair(weak, strong, wl='Слабый вариант', sl='Сильный вариант'):
    return '\n'.join([
        '  <div class="pair">',
        '    <div class="cell no"><p class="cell-h">%s</p><p>%s</p></div>' % (wl, esc(weak)),
        '    <div class="cell yes"><p class="cell-h">%s</p><p>%s</p></div>' % (sl, esc(strong)),
        '  </div>'])

def table(rows, lh, rh):
    tr = '\n'.join(
        '    <div class="trow"><p class="tl">%s</p><p class="tr">%s</p></div>' % (esc(a), esc(b))
        for a, b in rows)
    return '\n'.join(['  <div class="ttable">',
                      '    <div class="thead"><p>%s</p><p>%s</p></div>' % (esc(lh), esc(rh)),
                      tr, '  </div>'])

def callout(label, text):
    return ('  <div class="callout"><p class="co-l">%s</p><p>%s</p></div>'
            % (esc(label), esc(text)))

def part(n, title):
    return ('<div class="part">\n  <p class="part-n">%s</p>\n  <h2>%s</h2>\n</div>'
            % (esc(n), esc(title)))

def sec(*b):
    return '<section>\n%s\n</section>' % '\n'.join(x for x in b if x)

def h3(t):
    return '  <h3>%s</h3>' % esc(t)

def p(t):
    return '  <p>%s</p>' % esc(t)

def nums(items):
    return '  <ol class="steps">\n%s\n  </ol>' % '\n'.join(
        '    <li>%s</li>' % esc(i) for i in items)

def defs(items):
    return '  <div class="defs">\n%s\n  </div>' % '\n'.join(
        '    <div class="def"><p class="dt">%s</p><p class="dd">%s</p></div>' % (esc(a), esc(b))
        for a, b in items)

def marks(items):
    return '  <ul class="marks">\n%s\n  </ul>' % '\n'.join(
        '    <li>%s</li>' % esc(i) for i in items)

